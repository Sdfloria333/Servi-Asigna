package co.serviasigna.domain;

import jakarta.persistence.*;

/**
 * Una parada guardada (tabla PARADA): la recogida o la entrega de un servicio.
 * <p>
 * Guarda su estado (sección 6.2), a qué domiciliario y ruta pertenece, su orden en la ruta y las horas estimada y
 * real. El campo changed evita escribir en Oracle cuando nada cambió.
 * <p>
 * EN: A stored stop (PARADA table): the pickup or the drop-off of a delivery.
 * <p>
 * It keeps its status (section 6.2), which courier and route it belongs to, its order in the route and the
 * estimated and real times. The changed field avoids writing to Oracle when nothing changed.
 */
@Entity
@Table(name = "PARADA")
public class DeliveryStop {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;
    /** El id del servicio. EN: The delivery id. */
    @Column(name = "SERVICIO_ID", nullable = false) private Long deliveryId;
    /** El tipo de parada. EN: The stop type. */
    @Column(name = "TIPO", nullable = false, length = 10) private StopType type;
    /** El estado de la parada. EN: The stop status. */
    @Column(name = "ESTADO", nullable = false, length = 12) private StopStatus status = StopStatus.PENDING;
    /** El id del domiciliario. EN: The courier id. */
    @Column(name = "DOMICILIARIO_ID") private Long courierId;
    /** El id de la ruta. EN: The route id. */
    @Column(name = "RUTA_ID") private Long routeId;
    /** El orden dentro de la ruta. EN: The order within the route. */
    @Column(name = "SECUENCIA") private Integer sequence;
    /** La hora estimada de llegada. EN: The estimated arrival time. */
    @Convert(converter = MinutesConverter.class) @Column(name = "HORA_ESTIMADA") private Double estimatedTime;
    /** La hora real de llegada. EN: The real arrival time. */
    @Convert(converter = MinutesConverter.class) @Column(name = "HORA_LLEGADA") private Double arrivalTime;
    /** La hora en que se completó o falló. EN: The time it was completed or failed. */
    @Convert(converter = MinutesConverter.class) @Column(name = "HORA_FIN") private Double endTime;

    /** Si hay cambios sin guardar. EN: Whether there are unsaved changes. */
    @Transient private boolean changed;     // hay que guardarla

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected DeliveryStop() {}

    /**
     * Crea una parada pendiente.
     * <p>
     * EN: Creates a pending stop.
     *
     * @param deliveryId id del servicio / delivery id
     * @param type recoger o entregar / pickup or drop-off
     */
    public DeliveryStop(Long deliveryId, StopType type) { this.deliveryId = deliveryId; this.type = type; this.changed = true; }

    /**
     * Pasa al estado indicado (si es distinto) y anota la hora de llegada o de fin.
     * <p>
     * EN: Moves to the given status (if different) and records the arrival or end time.
     *
     * @param newStatus estado nuevo / new status
     * @param time hora en minutos de reloj / time in clock minutes
     */
    public void status(StopStatus newStatus, double time) {
        if (status == newStatus) return;
        status = newStatus;
        if (newStatus == StopStatus.AT_STOP && arrivalTime == null) arrivalTime = time;
        if (newStatus == StopStatus.COMPLETED || newStatus == StopStatus.FAILED) endTime = time;
        changed = true;
    }

    /**
     * Ubica la parada en la ruta de un domiciliario.
     * <p>
     * EN: Places the stop in the route of a courier.
     *
     * @param courierId id del domiciliario / courier id
     * @param routeId id de la ruta / route id
     * @param sequence orden dentro de la ruta / order within the route
     * @param estimatedTime hora estimada, puede ser null / estimated time, may be null
     */
    public void locate(Long courierId, Long routeId, Integer sequence, Double estimatedTime) {
        boolean different = !java.util.Objects.equals(this.courierId, courierId) || !java.util.Objects.equals(this.routeId, routeId)
                || !java.util.Objects.equals(this.sequence, sequence);
        // La hora estimada cambia un poco cada segundo: solo se guarda si se movió más de 1 minuto
        boolean movedAt = estimatedTime != null && (this.estimatedTime == null || Math.abs(this.estimatedTime - estimatedTime) >= 1);
        if (different || movedAt) changed = true;
        this.courierId = courierId; this.routeId = routeId; this.sequence = sequence;
        if (estimatedTime != null) this.estimatedTime = estimatedTime;
    }

    /**
     * Deja la parada libre otra vez porque el servicio regresó a la cola.
     * <p>
     * EN: Frees the stop again because the delivery went back to the queue.
     */
    public void release() {
        status = StopStatus.PENDING; courierId = null; routeId = null; sequence = null; estimatedTime = null; arrivalTime = null;
        changed = true;
    }

    /**
     * Indica si hay cambios por guardar y los da por tomados.
     * <p>
     * EN: Tells whether there are changes to save and marks them as taken.
     *
     * @return true si había cambios / true if there were changes
     */
    public boolean takeChange() { boolean c = changed; changed = false; return c; }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve el id del servicio.
     * <p>
     * EN: Returns the delivery id.
     *
     * @return el id del servicio / the delivery id
     */
    public Long getDeliveryId() { return deliveryId; }

    /**
     * Asigna el id del servicio (cuando el servicio se acaba de guardar).
     * <p>
     * EN: Sets the delivery id (when the delivery was just saved).
     *
     * @param id id del servicio / delivery id
     */
    public void setDeliveryId(Long id) { deliveryId = id; changed = true; }

    /**
     * Devuelve el tipo de parada.
     * <p>
     * EN: Returns the stop type.
     *
     * @return el tipo de parada / the stop type
     */
    public StopType getType() { return type; }

    /**
     * Devuelve el estado de la parada.
     * <p>
     * EN: Returns the stop status.
     *
     * @return el estado de la parada / the stop status
     */
    public StopStatus getStatus() { return status; }

    /**
     * Devuelve el id del domiciliario.
     * <p>
     * EN: Returns the courier id.
     *
     * @return el id del domiciliario / the courier id
     */
    public Long getCourierId() { return courierId; }

    /**
     * Devuelve el id de la ruta.
     * <p>
     * EN: Returns the route id.
     *
     * @return el id de la ruta / the route id
     */
    public Long getRouteId() { return routeId; }

    /**
     * Devuelve el orden dentro de la ruta.
     * <p>
     * EN: Returns the order within the route.
     *
     * @return el orden dentro de la ruta / the order within the route
     */
    public Integer getSequence() { return sequence; }

    /**
     * Devuelve la hora estimada de llegada.
     * <p>
     * EN: Returns the estimated arrival time.
     *
     * @return la hora estimada de llegada / the estimated arrival time
     */
    public Double getEstimatedTime() { return estimatedTime; }

    /**
     * Devuelve la hora real de llegada.
     * <p>
     * EN: Returns the real arrival time.
     *
     * @return la hora real de llegada / the real arrival time
     */
    public Double getArrivalTime() { return arrivalTime; }

    /**
     * Devuelve la hora en que se completó o falló.
     * <p>
     * EN: Returns the time it was completed or failed.
     *
     * @return la hora en que se completó o falló / the time it was completed or failed
     */
    public Double getEndTime() { return endTime; }
}

package co.serviasigna.domain;

import jakarta.persistence.*;

/**
 * Novedad o incidente (tabla INCIDENTE, RF-M6-08, RF-M7-02 a RF-M7-05).
 * <p>
 * La reporta el domiciliario o la central; la central comenta, decide (reintentar, liberar, cancelar o marcar
 * fallido) y la cierra.
 * <p>
 * EN: Incident (INCIDENTE table, RF-M6-08, RF-M7-02 to RF-M7-05).
 * <p>
 * The courier or the dispatch office reports it; the dispatch office comments, decides (retry, release, cancel or
 * mark failed) and closes it.
 */
@Entity
@Table(name = "INCIDENTE")
public class Incident {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY) private Long id;
    /** El tipo de novedad. EN: The incident type. */
    @Column(name = "TIPO", nullable = false, length = 20) private IncidentType type;
    /** El id del servicio. EN: The delivery id. */
    @Column(name = "SERVICIO_ID") private Long deliveryId;
    /** El id del domiciliario. EN: The courier id. */
    @Column(name = "DOMICILIARIO_ID") private Long courierId;
    /** El usuario que la reportó. EN: The user who reported it. */
    @Column(name = "REPORTADO_POR", nullable = false, length = 30) private String reportedBy;
    /** Lo que pasó. EN: What happened. */
    @Column(name = "DESCRIPCION", nullable = false, length = 500) private String description;
    /** La foto en base64. EN: The base64 photo. */
    @Lob @Column(name = "FOTO") private String photo;
    /** El estado de la novedad. EN: The incident status. */
    @Column(name = "ESTADO", nullable = false, length = 12) private IncidentStatus status = IncidentStatus.OPEN;
    /** La decisión tomada al cerrar. EN: The decision made when closing. */
    @Column(name = "DECISION", length = 15) private IncidentDecision decision;
    /** La explicación de la decisión. EN: The explanation of the decision. */
    @Column(name = "RESOLUCION", length = 500) private String resolution;
    /** La hora en que se abrió. EN: The time it was opened. */
    @Convert(converter = MinutesConverter.class) @Column(name = "ABIERTO", nullable = false) private Double opened;
    /** La hora en que se cerró. EN: The time it was closed. */
    @Convert(converter = MinutesConverter.class) @Column(name = "CERRADO") private Double closed;
    /** El usuario que la cerró. EN: The user who closed it. */
    @Column(name = "CERRADO_POR", length = 30) private String closedBy;

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected Incident() {}

    /**
     * Crea una novedad abierta.
     * <p>
     * EN: Creates an open incident.
     *
     * @param type tipo de novedad / incident type
     * @param deliveryId id del servicio, puede ser null / delivery id, may be null
     * @param courierId id del domiciliario, puede ser null / courier id, may be null
     * @param reportedBy usuario que la reporta / user who reports it
     * @param description qué pasó / what happened
     * @param photo foto en base64, puede ser null / base64 photo, may be null
     * @param time hora del reporte en minutos de reloj / report time in clock minutes
     */
    public Incident(IncidentType type, Long deliveryId, Long courierId, String reportedBy, String description, String photo, double time) {
        this.type = type; this.deliveryId = deliveryId; this.courierId = courierId; this.reportedBy = reportedBy;
        this.description = description; this.photo = photo; this.opened = time;
    }

    /**
     * Marca la novedad como en atención si todavía estaba abierta.
     * <p>
     * EN: Marks the incident as in progress if it was still open.
     */
    public void attend() { if (status == IncidentStatus.OPEN) status = IncidentStatus.IN_PROGRESS; }

    /**
     * Cierra la novedad con la decisión de la central.
     * <p>
     * EN: Closes the incident with the decision of the dispatch office.
     *
     * @param decision decisión tomada / decision made
     * @param resolution explicación de la decisión / explanation of the decision
     * @param username usuario que la cierra / user who closes it
     * @param time hora de cierre en minutos de reloj / closing time in clock minutes
     */
    public void close(IncidentDecision decision, String resolution, String username, double time) {
        this.decision = decision; this.resolution = resolution; this.closedBy = username; this.closed = time; status = IncidentStatus.CLOSED;
    }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve el tipo de novedad.
     * <p>
     * EN: Returns the incident type.
     *
     * @return el tipo de novedad / the incident type
     */
    public IncidentType getType() { return type; }

    /**
     * Devuelve el id del servicio.
     * <p>
     * EN: Returns the delivery id.
     *
     * @return el id del servicio / the delivery id
     */
    public Long getDeliveryId() { return deliveryId; }

    /**
     * Devuelve el id del domiciliario.
     * <p>
     * EN: Returns the courier id.
     *
     * @return el id del domiciliario / the courier id
     */
    public Long getCourierId() { return courierId; }

    /**
     * Devuelve el usuario que la reportó.
     * <p>
     * EN: Returns the user who reported it.
     *
     * @return el usuario que la reportó / the user who reported it
     */
    public String getReportedBy() { return reportedBy; }

    /**
     * Devuelve lo que pasó.
     * <p>
     * EN: Returns what happened.
     *
     * @return lo que pasó / what happened
     */
    public String getDescription() { return description; }

    /**
     * Devuelve la foto en base64.
     * <p>
     * EN: Returns the base64 photo.
     *
     * @return la foto en base64 / the base64 photo
     */
    public String getPhoto() { return photo; }

    /**
     * Devuelve el estado de la novedad.
     * <p>
     * EN: Returns the incident status.
     *
     * @return el estado de la novedad / the incident status
     */
    public IncidentStatus getStatus() { return status; }

    /**
     * Devuelve la decisión tomada al cerrar.
     * <p>
     * EN: Returns the decision made when closing.
     *
     * @return la decisión o null / the decision or null
     */
    public IncidentDecision getDecisionData() { return decision; }

    /**
     * Devuelve la explicación de la decisión.
     * <p>
     * EN: Returns the explanation of the decision.
     *
     * @return la explicación de la decisión / the explanation of the decision
     */
    public String getResolution() { return resolution; }

    /**
     * Devuelve la hora en que se abrió.
     * <p>
     * EN: Returns the time it was opened.
     *
     * @return la hora en que se abrió / the time it was opened
     */
    public Double getOpened() { return opened; }

    /**
     * Devuelve la hora en que se cerró.
     * <p>
     * EN: Returns the time it was closed.
     *
     * @return la hora en que se cerró / the time it was closed
     */
    public Double getClosed() { return closed; }

    /**
     * Devuelve el usuario que la cerró.
     * <p>
     * EN: Returns the user who closed it.
     *
     * @return el usuario que la cerró / the user who closed it
     */
    public String getClosedBy() { return closedBy; }
}

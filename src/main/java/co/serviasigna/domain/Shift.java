package co.serviasigna.domain;

import jakarta.persistence.*;

/**
 * Turno de un domiciliario (tabla TURNO): desde que se pone disponible hasta que sale de servicio.
 * <p>
 * Lleva los servicios completados, lo cobrado (recaudo, RF-M8-02), lo que ya entregó a la central (cuadre,
 * RF-M8-03) y sus ganancias (RF-M6-12). El estado se guarda en español: "ABIERTO" o "CERRADO".
 * <p>
 * EN: Shift of a courier (TURNO table): from when they become available until they go off duty.
 * <p>
 * It keeps the completed deliveries, the money collected (RF-M8-02), what was already handed over to the dispatch
 * office (cash reconciliation, RF-M8-03) and the earnings (RF-M6-12). The status is stored in Spanish: "ABIERTO"
 * (open) or "CERRADO" (closed).
 */
@Entity
@Table(name = "TURNO")
public class Shift {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY) private Long id;
    /** El id del domiciliario. EN: The courier id. */
    @Column(name = "DOMICILIARIO_ID", nullable = false) private Long courierId;
    /** La hora de inicio. EN: The start time. */
    @Convert(converter = MinutesConverter.class) @Column(name = "INICIO", nullable = false) private Double start;
    /** La hora de cierre. EN: The closing time. */
    @Convert(converter = MinutesConverter.class) @Column(name = "FIN") private Double end;
    /** El número de servicios completados. EN: The number of completed deliveries. */
    @Column(name = "COMPLETADOS", nullable = false) private int completed;
    /** El dinero cobrado en el turno, en pesos. EN: The money collected in the shift, in pesos. */
    @Column(name = "RECAUDO", nullable = false) private long collected;

    /**
     * El dinero ya entregado a la central, en pesos.
     * <p>
     * EN: The money already handed over to the dispatch office, in pesos.
     */
    @Column(name = "RECAUDO_ENTREGADO", nullable = false) private long collectedHandedOver;
    /** Las ganancias del domiciliario, en pesos. EN: The courier earnings, in pesos. */
    @Column(name = "GANANCIAS", nullable = false) private long earnings;
    /** Los kilómetros recorridos. EN: The kilometers travelled. */
    @Column(name = "KM_RECORRIDOS", nullable = false) private double kmTravelled;      // indicador I4
    /** El estado: "ABIERTO" o "CERRADO". EN: The status: "ABIERTO" or "CERRADO". */
    @Column(name = "ESTADO", nullable = false, length = 10) private String status = "ABIERTO";

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected Shift() {}

    /**
     * Abre un turno.
     * <p>
     * EN: Opens a shift.
     *
     * @param courierId id del domiciliario / courier id
     * @param start hora de inicio en minutos de reloj / start time in clock minutes
     */
    public Shift(long courierId, double start) { this.courierId = courierId; this.start = start; }

    /**
     * Suma un servicio entregado con lo que se cobró y lo que gana el domiciliario.
     * <p>
     * EN: Adds a delivered order with the money collected and what the courier earns.
     *
     * @param amountCollected dinero cobrado al cliente (0 si era prepagado) / money collected from the customer (0
     *     if prepaid)
     * @param earning lo que gana el domiciliario / what the courier earns
     */
    public void addDelivered(long amountCollected, long earning) { completed++; collected += amountCollected; earnings += earning; }

    /**
     * Registra dinero que el domiciliario entregó a la central.
     * <p>
     * EN: Records money the courier handed over to the dispatch office.
     *
     * @param value valor entregado en pesos / amount handed over in pesos
     */
    public void receiveCollection(long value) { collectedHandedOver += value; }

    /**
     * Suma kilómetros recorridos.
     * <p>
     * EN: Adds kilometers travelled.
     *
     * @param km kilómetros / kilometers
     */
    public void addKm(double km) { kmTravelled += km; }

    /**
     * Cierra el turno.
     * <p>
     * EN: Closes the shift.
     *
     * @param time hora de cierre en minutos de reloj / closing time in clock minutes
     */
    public void close(double time) { end = time; status = "CERRADO"; }

    /**
     * Calcula el dinero cobrado que todavía no entregó a la central.
     * <p>
     * EN: Computes the money collected that has not been handed over to the dispatch office yet.
     *
     * @return el saldo pendiente en pesos / the pending balance in pesos
     */
    public long getPending() { return collected - collectedHandedOver; }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve el id del domiciliario.
     * <p>
     * EN: Returns the courier id.
     *
     * @return el id del domiciliario / the courier id
     */
    public Long getCourierId() { return courierId; }

    /**
     * Devuelve la hora de inicio.
     * <p>
     * EN: Returns the start time.
     *
     * @return la hora de inicio / the start time
     */
    public Double getStart() { return start; }

    /**
     * Devuelve la hora de cierre.
     * <p>
     * EN: Returns the closing time.
     *
     * @return la hora de cierre / the closing time
     */
    public Double getEnd() { return end; }

    /**
     * Devuelve el número de servicios completados.
     * <p>
     * EN: Returns the number of completed deliveries.
     *
     * @return el número de servicios completados / the number of completed deliveries
     */
    public int getCompleted() { return completed; }

    /**
     * Devuelve el dinero cobrado en el turno, en pesos.
     * <p>
     * EN: Returns the money collected in the shift, in pesos.
     *
     * @return el dinero cobrado en el turno, en pesos / the money collected in the shift, in pesos
     */
    public long getCollected() { return collected; }

    /**
     * Devuelve el dinero ya entregado a la central, en pesos.
     * <p>
     * EN: Returns the money already handed over to the dispatch office, in pesos.
     *
     * @return el dinero ya entregado a la central, en pesos / the money already handed over to the dispatch office,
     *     in pesos
     */
    public long getCollectedHandedOver() { return collectedHandedOver; }

    /**
     * Devuelve las ganancias del domiciliario, en pesos.
     * <p>
     * EN: Returns the courier earnings, in pesos.
     *
     * @return las ganancias del domiciliario, en pesos / the courier earnings, in pesos
     */
    public long getEarnings() { return earnings; }

    /**
     * Devuelve el estado: "ABIERTO" o "CERRADO".
     * <p>
     * EN: Returns the status: "ABIERTO" or "CERRADO".
     *
     * @return el estado: "ABIERTO" o "CERRADO" / the status: "ABIERTO" or "CERRADO"
     */
    public String getStatus() { return status; }

    /**
     * Devuelve los kilómetros recorridos.
     * <p>
     * EN: Returns the kilometers travelled.
     *
     * @return los kilómetros recorridos / the kilometers travelled
     */
    public double getKmTravelled() { return kmTravelled; }
}

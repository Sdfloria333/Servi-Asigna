package co.serviasigna.domain;

import jakarta.persistence.*;

/**
 * Regla de precio (tabla TARIFA, RF-M2-07). Valor = base + km × perKm + recargo por tamaño, nunca menos que el
 * mínimo.
 * <p>
 * Todo va en pesos colombianos sin decimales (RN-17). courierPercentage es la regla de pago al domiciliario
 * (DA-01).
 * <p>
 * EN: Pricing rule (TARIFA table, RF-M2-07). Value = base + km × perKm + size surcharge, never less than the minimum.
 * <p>
 * Everything is in Colombian pesos without decimals (RN-17). courierPercentage is the courier payment rule (DA-01).
 */
@Entity
@Table(name = "TARIFA")
public class Rate {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY) private Long id;
    /** El nombre de la tarifa. EN: The rate name. */
    @Column(name = "NOMBRE", nullable = false, length = 60) private String name;
    /** El valor base. EN: The base value. */
    @Column(name = "BASE", nullable = false) private long base;
    /** El valor por kilómetro. EN: The value per kilometer. */
    @Column(name = "POR_KM", nullable = false) private long perKm;
    /** El recargo por paquete mediano. EN: The medium package surcharge. */
    @Column(name = "RECARGO_MEDIANO", nullable = false) private long mediumSurcharge;
    /** El recargo por paquete grande. EN: The large package surcharge. */
    @Column(name = "RECARGO_GRANDE", nullable = false) private long largeSurcharge;
    /** El valor mínimo. EN: The minimum value. */
    @Column(name = "MINIMO", nullable = false) private long minimum;
    /** El porcentaje para el domiciliario. EN: The percentage for the courier. */
    @Column(name = "PORCENTAJE_DOMICILIARIO", nullable = false) private int courierPercentage;
    /** Si la tarifa está activa. EN: Whether the rate is active. */
    @Column(name = "ACTIVA", nullable = false) private boolean active = true;

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected Rate() {}

    /**
     * Crea una tarifa activa.
     * <p>
     * EN: Creates an active rate.
     *
     * @param name nombre de la tarifa / rate name
     * @param base valor base / base value
     * @param perKm valor por kilómetro / value per kilometer
     * @param mediumSurcharge recargo por paquete mediano / medium package surcharge
     * @param largeSurcharge recargo por paquete grande / large package surcharge
     * @param minimum valor mínimo / minimum value
     * @param courierPercentage porcentaje para el domiciliario / percentage for the courier
     */
    public Rate(String name, long base, long perKm, long mediumSurcharge, long largeSurcharge, long minimum, int courierPercentage) {
        this.name = name; this.base = base; this.perKm = perKm; this.mediumSurcharge = mediumSurcharge;
        this.largeSurcharge = largeSurcharge; this.minimum = minimum; this.courierPercentage = courierPercentage;
    }

    /**
     * Calcula el valor del servicio, redondeado a 100 pesos.
     * <p>
     * EN: Computes the delivery value, rounded to 100 pesos.
     *
     * @param km distancia del recorrido / trip distance
     * @param size tamaño del paquete / package size
     * @return el valor en pesos / the value in pesos
     */
    public long valueFor(double km, PackageSize size) {
        double v = base + km * perKm + (size == PackageSize.MEDIUM ? mediumSurcharge : size == PackageSize.LARGE ? largeSurcharge : 0);
        return Math.max(minimum, Math.round(v / 100.0) * 100);
    }

    /**
     * Calcula lo que gana el domiciliario por un servicio.
     * <p>
     * EN: Computes what the courier earns for a delivery.
     *
     * @param value valor del servicio / delivery value
     * @return el pago en pesos / the payment in pesos
     */
    public long courierPay(long value) { return Math.round(value * courierPercentage / 100.0); }

    /**
     * Desactiva la tarifa.
     * <p>
     * EN: Deactivates the rate.
     */
    public void deactivate() { active = false; }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve el nombre de la tarifa.
     * <p>
     * EN: Returns the rate name.
     *
     * @return el nombre de la tarifa / the rate name
     */
    public String getName() { return name; }

    /**
     * Devuelve el valor base.
     * <p>
     * EN: Returns the base value.
     *
     * @return el valor base / the base value
     */
    public long getBase() { return base; }

    /**
     * Devuelve el valor por kilómetro.
     * <p>
     * EN: Returns the value per kilometer.
     *
     * @return el valor por kilómetro / the value per kilometer
     */
    public long getPerKm() { return perKm; }

    /**
     * Devuelve el recargo por paquete mediano.
     * <p>
     * EN: Returns the medium package surcharge.
     *
     * @return el recargo por paquete mediano / the medium package surcharge
     */
    public long getMediumSurcharge() { return mediumSurcharge; }

    /**
     * Devuelve el recargo por paquete grande.
     * <p>
     * EN: Returns the large package surcharge.
     *
     * @return el recargo por paquete grande / the large package surcharge
     */
    public long getLargeSurcharge() { return largeSurcharge; }

    /**
     * Devuelve el valor mínimo.
     * <p>
     * EN: Returns the minimum value.
     *
     * @return el valor mínimo / the minimum value
     */
    public long getMinimum() { return minimum; }

    /**
     * Devuelve el porcentaje para el domiciliario.
     * <p>
     * EN: Returns the percentage for the courier.
     *
     * @return el porcentaje para el domiciliario / the percentage for the courier
     */
    public int getCourierPercentage() { return courierPercentage; }

    /**
     * Indica si la tarifa está activa.
     * <p>
     * EN: Tells whether the rate is active.
     *
     * @return true si se cumple / true if it applies
     */
    public boolean isActive() { return active; }
}

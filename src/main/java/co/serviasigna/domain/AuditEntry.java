package co.serviasigna.domain;

import jakarta.persistence.*;

/**
 * Registro de una operación crítica (tabla AUDITORIA, RF-M1-05, RNF-11). Solo se inserta, nunca se modifica.
 * <p>
 * manualIntervention marca las acciones de la central sobre la asignación (indicador I7: carga de la central). Los
 * códigos de acción se guardan en español, por ejemplo CREAR_CUENTA.
 * <p>
 * EN: Record of a critical operation (AUDITORIA table, RF-M1-05, RNF-11). It is only inserted, never modified.
 * <p>
 * manualIntervention marks the actions of the dispatch office on the assignment (indicator I7: dispatch office
 * load). Action codes are stored in Spanish, for example CREAR_CUENTA (create account).
 */
@Entity
@Table(name = "AUDITORIA")
public class AuditEntry {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY) private Long id;
    /** La fecha en minutos de reloj. EN: The date in clock minutes. */
    @Convert(converter = MinutesConverter.class) @Column(name = "FECHA", nullable = false) private Double date;
    /** Quién hizo la acción. EN: Who did the action. */
    @Column(name = "USUARIO", nullable = false, length = 30) private String username;
    /** El código de la acción. EN: The action code. */
    @Column(name = "ACCION", nullable = false, length = 40) private String action;
    /** La tabla afectada. EN: The affected table. */
    @Column(name = "ENTIDAD", length = 30) private String entity;
    /** El id del registro afectado. EN: The id of the affected record. */
    @Column(name = "ENTIDAD_ID") private Long entityId;
    /** El detalle de la acción. EN: The detail of the action. */
    @Column(name = "DETALLE", length = 500) private String detail;
    /** Si es una intervención manual de la central. EN: Whether it is a manual intervention of the dispatch office. */
    @Column(name = "INTERVENCION_MANUAL", nullable = false) private boolean manualIntervention;

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected AuditEntry() {}

    /**
     * Crea un registro de auditoría.
     * <p>
     * EN: Creates an audit record.
     *
     * @param date fecha en minutos de reloj / date in clock minutes
     * @param username quién hizo la acción / who did the action
     * @param action código de la acción / action code
     * @param entity tabla afectada / affected table
     * @param entityId id del registro afectado / id of the affected record
     * @param detail detalle, puede ser null / detail, may be null
     * @param manualIntervention true si es una intervención de la central / true if it is an intervention of the
     *     dispatch office
     */
    public AuditEntry(double date, String username, String action, String entity, Long entityId, String detail, boolean manualIntervention) {
        this.date = date; this.username = username; this.action = action; this.entity = entity;
        this.entityId = entityId; this.detail = detail; this.manualIntervention = manualIntervention;
    }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve la fecha en minutos de reloj.
     * <p>
     * EN: Returns the date in clock minutes.
     *
     * @return la fecha en minutos de reloj / the date in clock minutes
     */
    public Double getDate() { return date; }

    /**
     * Devuelve quién hizo la acción.
     * <p>
     * EN: Returns the who did the action.
     *
     * @return quién hizo la acción / the who did the action
     */
    public String getUsername() { return username; }

    /**
     * Devuelve el código de la acción.
     * <p>
     * EN: Returns the action code.
     *
     * @return el código de la acción / the action code
     */
    public String getAction() { return action; }

    /**
     * Devuelve la tabla afectada.
     * <p>
     * EN: Returns the affected table.
     *
     * @return la tabla afectada / the affected table
     */
    public String getEntity() { return entity; }

    /**
     * Devuelve el id del registro afectado.
     * <p>
     * EN: Returns the id of the affected record.
     *
     * @return el id del registro afectado / the id of the affected record
     */
    public Long getEntityId() { return entityId; }

    /**
     * Devuelve el detalle de la acción.
     * <p>
     * EN: Returns the detail of the action.
     *
     * @return el detalle de la acción / the detail of the action
     */
    public String getDetail() { return detail; }

    /**
     * Indica si es una intervención manual de la central.
     * <p>
     * EN: Tells whether it is a manual intervention of the dispatch office.
     *
     * @return true si se cumple / true if it applies
     */
    public boolean isManualIntervention() { return manualIntervention; }
}

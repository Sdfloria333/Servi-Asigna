package co.serviasigna.domain;

import jakarta.persistence.*;

/**
 * Una decisión del motor (tabla DECISION_MOTOR, RF-M5-09): a quién consideró, cuánto costaba cada uno y a quién
 * eligió.
 * <p>
 * Los candidatos se guardan como texto "courierId:costo;courierId:costo..." ordenados por costo.
 * <p>
 * EN: An engine decision (DECISION_MOTOR table, RF-M5-09): whom it considered, how much each one cost and whom it
 * chose.
 * <p>
 * The candidates are stored as the text "courierId:cost;courierId:cost..." sorted by cost.
 */
@Entity
@Table(name = "DECISION_MOTOR")
public class EngineDecision {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY) private Long id;
    /** El id del servicio. EN: The delivery id. */
    @Column(name = "SERVICIO_ID", nullable = false) private Long deliveryId;
    /** La fecha en minutos de reloj. EN: The date in clock minutes. */
    @Convert(converter = MinutesConverter.class) @Column(name = "FECHA", nullable = false) private Double date;
    /** El modo de asignación. EN: The assignment mode. */
    @Column(name = "MODO", nullable = false, length = 12) private AssignmentMode mode;
    /** El id del domiciliario elegido. EN: The id of the chosen courier. */
    @Column(name = "ELEGIDO_ID") private Long chosenId;
    /** El costo del elegido. EN: The cost of the chosen one. */
    @Column(name = "COSTO") private Double cost;
    /** Los candidatos con su costo. EN: The candidates with their cost. */
    @Column(name = "CANDIDATOS", length = 2000) private String candidates;

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected EngineDecision() {}

    /**
     * Crea la decisión; recorta los candidatos a 2000 caracteres si hace falta.
     * <p>
     * EN: Creates the decision; trims the candidates to 2000 characters if needed.
     *
     * @param deliveryId id del servicio / delivery id
     * @param date fecha en minutos de reloj / date in clock minutes
     * @param mode modo de asignación / assignment mode
     * @param chosenId id del domiciliario elegido, puede ser null / id of the chosen courier, may be null
     * @param cost costo del elegido / cost of the chosen one
     * @param candidates candidatos con su costo / candidates with their cost
     */
    public EngineDecision(long deliveryId, double date, AssignmentMode mode, Long chosenId, Double cost, String candidates) {
        this.deliveryId = deliveryId; this.date = date; this.mode = mode; this.chosenId = chosenId; this.cost = cost;
        this.candidates = candidates == null || candidates.length() <= 2000 ? candidates : candidates.substring(0, 2000);
    }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve el id del servicio.
     * <p>
     * EN: Returns the delivery id.
     *
     * @return el id del servicio / the delivery id
     */
    public Long getDeliveryId() { return deliveryId; }

    /**
     * Devuelve la fecha en minutos de reloj.
     * <p>
     * EN: Returns the date in clock minutes.
     *
     * @return la fecha en minutos de reloj / the date in clock minutes
     */
    public Double getDate() { return date; }

    /**
     * Devuelve el modo de asignación.
     * <p>
     * EN: Returns the assignment mode.
     *
     * @return el modo de asignación / the assignment mode
     */
    public AssignmentMode getMode() { return mode; }

    /**
     * Devuelve el id del domiciliario elegido.
     * <p>
     * EN: Returns the id of the chosen courier.
     *
     * @return el id del domiciliario elegido / the id of the chosen courier
     */
    public Long getChosenId() { return chosenId; }

    /**
     * Devuelve el costo del elegido.
     * <p>
     * EN: Returns the cost of the chosen one.
     *
     * @return el costo del elegido / the cost of the chosen one
     */
    public Double getCost() { return cost; }

    /**
     * Devuelve los candidatos con su costo.
     * <p>
     * EN: Returns the candidates with their cost.
     *
     * @return los candidatos con su costo / the candidates with their cost
     */
    public String getCandidates() { return candidates; }
}

package co.serviasigna.domain;

import jakarta.persistence.*;

/**
 * Mensaje predefinido para escribir rápido (tabla PLANTILLA_MENSAJE, RF-M4-06).
 * <p>
 * El campo forRole dice quién la usa y se guarda en español: "CENTRAL" o "DOMICILIARIO".
 * <p>
 * EN: Predefined message to write quickly (PLANTILLA_MENSAJE table, RF-M4-06).
 * <p>
 * The forRole field tells who uses it and is stored in Spanish: "CENTRAL" (dispatch office) or "DOMICILIARIO"
 * (courier).
 */
@Entity
@Table(name = "PLANTILLA_MENSAJE")
public class MessageTemplate {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY) private Long id;
    /** El texto del mensaje. EN: The message text. */
    @Column(name = "TEXTO", nullable = false, length = 200) private String text;
    /** Quién usa la plantilla: "CENTRAL" o "DOMICILIARIO". EN: Who uses the template: "CENTRAL" or "DOMICILIARIO". */
    @Column(name = "PARA_ROL", nullable = false, length = 15) private String forRole;
    /** Si la plantilla está activa. EN: Whether the template is active. */
    @Column(name = "ACTIVA", nullable = false) private boolean active = true;

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected MessageTemplate() {}

    /**
     * Crea una plantilla activa.
     * <p>
     * EN: Creates an active template.
     *
     * @param text texto del mensaje / message text
     * @param forRole "CENTRAL" o "DOMICILIARIO" / "CENTRAL" or "DOMICILIARIO"
     */
    public MessageTemplate(String text, String forRole) { this.text = text; this.forRole = forRole; }

    /**
     * Desactiva la plantilla: deja de aparecer, pero no se borra.
     * <p>
     * EN: Deactivates the template: it no longer shows up, but it is not deleted.
     */
    public void deactivate() { active = false; }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve el texto del mensaje.
     * <p>
     * EN: Returns the message text.
     *
     * @return el texto del mensaje / the message text
     */
    public String getText() { return text; }

    /**
     * Devuelve quién usa la plantilla: "CENTRAL" o "DOMICILIARIO".
     * <p>
     * EN: Returns the who uses the template: "CENTRAL" or "DOMICILIARIO".
     *
     * @return quién usa la plantilla: "CENTRAL" o "DOMICILIARIO" / the who uses the template: "CENTRAL" or
     *     "DOMICILIARIO"
     */
    public String getForRole() { return forRole; }

    /**
     * Indica si la plantilla está activa.
     * <p>
     * EN: Tells whether the template is active.
     *
     * @return true si se cumple / true if it applies
     */
    public boolean isActive() { return active; }
}

package co.serviasigna.domain;

import jakarta.persistence.*;

/**
 * Un cambio de estado de un servicio: quién, cuándo, desde dónde y por qué (tabla HISTORIAL_ESTADO_SERVICIO,
 * RN-01).
 * <p>
 * El origen se guarda en español: CENTRAL, DOMICILIARIO, MOTOR o SISTEMA.
 * <p>
 * EN: A status change of a delivery: who, when, from where and why (HISTORIAL_ESTADO_SERVICIO table, RN-01).
 * <p>
 * The origin is stored in Spanish: CENTRAL (dispatch office), DOMICILIARIO (courier), MOTOR (engine) or SISTEMA
 * (system).
 */
@Entity
@Table(name = "HISTORIAL_ESTADO_SERVICIO")
public class StatusChange {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY) private Long id;
    /** El id del servicio. EN: The delivery id. */
    @Column(name = "SERVICIO_ID", nullable = false) private Long deliveryId;
    /** El estado anterior. EN: The previous status. */
    @Column(name = "ESTADO_ANTERIOR", length = 20) private DeliveryStatus previous;
    /** El estado nuevo. EN: The new status. */
    @Column(name = "ESTADO_NUEVO", nullable = false, length = 20) private DeliveryStatus newStatus;
    /** La fecha en minutos de reloj. EN: The date in clock minutes. */
    @Convert(converter = MinutesConverter.class) @Column(name = "FECHA", nullable = false) private Double date;
    /** El usuario que hizo el cambio. EN: The user who made the change. */
    @Column(name = "USUARIO", length = 30) private String username;

    /**
     * El origen del cambio: CENTRAL, DOMICILIARIO, MOTOR o SISTEMA.
     * <p>
     * EN: The origin of the change: CENTRAL, DOMICILIARIO, MOTOR or SISTEMA.
     */
    @Column(name = "ORIGEN", nullable = false, length = 15) private String origin;     // CENTRAL, DOMICILIARIO, MOTOR, SISTEMA
    /** El motivo del cambio. EN: The reason for the change. */
    @Column(name = "MOTIVO", length = 300) private String reason;

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected StatusChange() {}

    /**
     * Crea una fila del historial.
     * <p>
     * EN: Creates a history row.
     *
     * @param deliveryId id del servicio / delivery id
     * @param previous estado anterior, null si es el primero / previous status, null if it is the first one
     * @param newStatus estado nuevo / new status
     * @param date fecha en minutos de reloj / date in clock minutes
     * @param username usuario que hizo el cambio / user who made the change
     * @param origin CENTRAL, DOMICILIARIO, MOTOR o SISTEMA / CENTRAL, DOMICILIARIO, MOTOR or SISTEMA
     * @param reason motivo, puede ser null / reason, may be null
     */
    public StatusChange(long deliveryId, DeliveryStatus previous, DeliveryStatus newStatus, double date, String username, String origin, String reason) {
        this.deliveryId = deliveryId; this.previous = previous; this.newStatus = newStatus; this.date = date;
        this.username = username; this.origin = origin; this.reason = reason;
    }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve el id del servicio.
     * <p>
     * EN: Returns the delivery id.
     *
     * @return el id del servicio / the delivery id
     */
    public Long getDeliveryId() { return deliveryId; }

    /**
     * Devuelve el estado anterior.
     * <p>
     * EN: Returns the previous status.
     *
     * @return el estado anterior o null / the previous status or null
     */
    public DeliveryStatus getPreviousStatus() { return previous; }

    /**
     * Devuelve el estado nuevo.
     * <p>
     * EN: Returns the new status.
     *
     * @return el estado nuevo / the new status
     */
    public DeliveryStatus getNewStatus() { return newStatus; }

    /**
     * Devuelve la fecha en minutos de reloj.
     * <p>
     * EN: Returns the date in clock minutes.
     *
     * @return la fecha en minutos de reloj / the date in clock minutes
     */
    public Double getDate() { return date; }

    /**
     * Devuelve el usuario que hizo el cambio.
     * <p>
     * EN: Returns the user who made the change.
     *
     * @return el usuario que hizo el cambio / the user who made the change
     */
    public String getUsername() { return username; }

    /**
     * Devuelve el origen del cambio: CENTRAL, DOMICILIARIO, MOTOR o SISTEMA.
     * <p>
     * EN: Returns the origin of the change: CENTRAL, DOMICILIARIO, MOTOR or SISTEMA.
     *
     * @return el origen del cambio: CENTRAL, DOMICILIARIO, MOTOR o SISTEMA / the origin of the change: CENTRAL,
     *     DOMICILIARIO, MOTOR or SISTEMA
     */
    public String getOrigin() { return origin; }

    /**
     * Devuelve el motivo del cambio.
     * <p>
     * EN: Returns the reason for the change.
     *
     * @return el motivo del cambio / the reason for the change
     */
    public String getReason() { return reason; }
}

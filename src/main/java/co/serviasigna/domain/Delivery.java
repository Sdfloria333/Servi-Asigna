    /**
     * Cambia lo que gana el domiciliario por este servicio.
     * <p>
     * EN: Changes what the courier earns for this delivery.
     *
     * @param payment el nuevo valor / the new value
     */
    public void setCourierPay(Long payment) { courierPay = payment; }

    /**
     * Edita los datos del pedido desde la central (RF-M3-03); nunca cambia el estado.
     * <p>
     * EN: Edits the order data from the dispatch office (RF-M3-03); it never changes the status.
     *
     * @param note detalle del pedido / order detail
     * @param customer nombre del cliente / customer name
     * @param phone teléfono / phone
     * @param size tamaño / size
     * @param priority prioridad / priority
     * @param paymentMethod forma de pago / payment method
     * @param value valor en pesos / value in pesos
     * @param readyAt hora en que estará listo / time it will be ready
     * @param pickupDeadline hora máxima de recogida / latest pickup time
     * @param deadline hora máxima de entrega / latest drop-off time
     */
    public void edit(String note, String customer, String phone, PackageSize size, Priority priority,
                       PaymentMethod paymentMethod, long value, double readyAt, double pickupDeadline, double deadline) {
        this.note = note; this.customer = customer; this.phone = phone; this.size = size; this.priority = priority;
        this.paymentMethod = paymentMethod; this.value = value; this.readyAt = readyAt; this.pickupDeadline = pickupDeadline; this.deadline = deadline;
    }

    /**
     * Indica si el servicio sigue abierto (no está entregado, fallido ni cancelado).
     * <p>
     * EN: Tells whether the delivery is still open (not delivered, failed or cancelled).
     *
     * @return true si está abierto / true if open
     */
    public boolean isOpen() { return status.isOpen(); }


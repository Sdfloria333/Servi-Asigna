    /**
     * Registra lo que cobró el domiciliario y lo que gana.
     * <p>
     * EN: Records what the courier collected and what they earn.
     *
     * @param received valor recibido del cliente, puede ser null / amount received from the customer, may be null
     * @param payment pago al domiciliario / courier payment
     */

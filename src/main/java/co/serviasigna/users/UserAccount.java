package co.serviasigna.users;

import co.serviasigna.domain.AccountStatus;
import jakarta.persistence.*;
import java.time.LocalDateTime;

/**
 * Una cuenta de usuario (tabla USUARIO). Se entra con nombre de usuario y contraseña (hash BCrypt, RNF-07).
 * <p>
 * Un domiciliario se registra solo y queda PENDING hasta que la central lo aprueba (una sola vez). La cuenta nunca
 * se borra: se desactiva, suspende o rechaza (borrado lógico, RN-16). currentSession guarda la única sesión válida
 * (RF-M1-04: una sola sesión por domiciliario).
 * <p>
 * EN: A user account (USUARIO table). Users log in with username and password (BCrypt hash, RNF-07).
 * <p>
 * A courier signs up alone and stays PENDING until the dispatch office approves them (only once). The account is
 * never deleted: it is deactivated, suspended or rejected (soft delete, RN-16). currentSession keeps the only valid
 * session (RF-M1-04: one session per courier).
 */
@Entity
@Table(name = "USUARIO")
public class UserAccount {
    /** El identificador que genera Oracle. EN: The identifier generated by Oracle. */
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY) private Long id;
    /** El nombre de la persona. EN: The person name. */
    @Column(name = "NOMBRE", nullable = false, length = 80) private String name;
    /** El nombre de usuario (único). EN: The username (unique). */
    @Column(name = "USUARIO", nullable = false, unique = true, length = 30) private String username;
    /** El hash BCrypt de la contraseña. EN: The BCrypt hash of the password. */
    @Column(name = "CLAVE", nullable = false, length = 100) private String password;
    /** El rol de la cuenta. EN: The account role. */
    @Column(name = "ROL", nullable = false, length = 15) private Role role;
    /** El estado de la cuenta. EN: The account status. */
    @Column(name = "ESTADO_CUENTA", nullable = false, length = 12) private AccountStatus accountStatus;
    /** Si debe cambiar la contraseña al entrar. EN: Whether the password must be changed at login. */
    @Column(name = "DEBE_CAMBIAR_CLAVE", nullable = false) private boolean mustChangePassword;
    /** El id de la única sesión válida. EN: The id of the only valid session. */
    @Column(name = "SESION_ACTUAL", length = 40) private String currentSession;
    /** La fecha de creación. EN: The creation date. */
    @Column(name = "CREADO", nullable = false) private LocalDateTime created = LocalDateTime.now();
    /** La fecha del último ingreso. EN: The last login date. */
    @Column(name = "ULTIMO_INGRESO") private LocalDateTime lastLogin;

    /**
     * Constructor vacío que exige JPA para leer la fila de la base de datos.
     * <p>
     * EN: Empty constructor required by JPA to read the row from the database.
     */
    protected UserAccount() {}

    /**
     * Crea una cuenta.
     * <p>
     * EN: Creates an account.
     *
     * @param name nombre de la persona / person name
     * @param username nombre de usuario, único / username, unique
     * @param password hash BCrypt de la contraseña / BCrypt hash of the password
     * @param role rol / role
     * @param status estado inicial / initial status
     */
    public UserAccount(String name, String username, String password, Role role, AccountStatus status) {
        this.name = name; this.username = username; this.password = password; this.role = role; this.accountStatus = status;
    }

    /**
     * Cambia el estado de la cuenta.
     * <p>
     * EN: Changes the account status.
     *
     * @param e el nuevo valor / the new value
     */
    public void setAccountStatus(AccountStatus e) { accountStatus = e; }

    /**
     * Cambia la contraseña.
     * <p>
     * EN: Changes the password.
     *
     * @param hash hash BCrypt de la nueva contraseña / BCrypt hash of the new password
     * @param temporary true si es temporal y debe cambiarla al entrar / true if it is temporary and must be changed
     *     at login
     */
    public void changePassword(String hash, boolean temporary) { password = hash; mustChangePassword = temporary; }

    /**
     * Registra un ingreso: guarda la sesión nueva y la fecha.
     * <p>
     * EN: Records a login: stores the new session and the date.
     *
     * @param session id de la sesión nueva / new session id
     */
    public void login(String session) { currentSession = session; lastLogin = LocalDateTime.now(); }

    /**
     * Cambia el nombre de la persona.
     * <p>
     * EN: Changes the person name.
     *
     * @param n el nuevo valor / the new value
     */
    public void setName(String n) { name = n; }

    /**
     * Indica si la cuenta está activa y puede entrar.
     * <p>
     * EN: Tells whether the account is active and can log in.
     *
     * @return true si está activa / true if active
     */
    public boolean isActive() { return accountStatus == AccountStatus.ACTIVE; }

    /**
     * Indica si la cuenta ya fue aprobada (no está pendiente ni rechazada).
     * <p>
     * EN: Tells whether the account was already approved (it is neither pending nor rejected).
     *
     * @return true si fue aprobada / true if approved
     */
    public boolean isApproved() { return accountStatus != AccountStatus.PENDING && accountStatus != AccountStatus.REJECTED; }

    /**
     * Devuelve el identificador que genera Oracle.
     * <p>
     * EN: Returns the identifier generated by Oracle.
     *
     * @return el identificador que genera Oracle / the identifier generated by Oracle
     */
    public Long getId() { return id; }

    /**
     * Devuelve el nombre de la persona.
     * <p>
     * EN: Returns the person name.
     *
     * @return el nombre de la persona / the person name
     */
    public String getName() { return name; }

    /**
     * Devuelve el nombre de usuario (único).
     * <p>
     * EN: Returns the username (unique).
     *
     * @return el nombre de usuario (único) / the username (unique)
     */
    public String getUsername() { return username; }

    /**
     * Devuelve el hash BCrypt de la contraseña.
     * <p>
     * EN: Returns the BCrypt hash of the password.
     *
     * @return el hash BCrypt de la contraseña / the BCrypt hash of the password
     */
    public String getPassword() { return password; }

    /**
     * Devuelve el rol de la cuenta.
     * <p>
     * EN: Returns the account role.
     *
     * @return el rol de la cuenta / the account role
     */
    public Role getRole() { return role; }

    /**
     * Devuelve el estado de la cuenta.
     * <p>
     * EN: Returns the account status.
     *
     * @return el estado de la cuenta / the account status
     */
    public AccountStatus getAccountStatus() { return accountStatus; }

    /**
     * Indica si debe cambiar la contraseña al entrar.
     * <p>
     * EN: Tells whether the password must be changed at login.
     *
     * @return true si se cumple / true if it applies
     */
    public boolean isMustChangePassword() { return mustChangePassword; }

    /**
     * Devuelve el id de la única sesión válida.
     * <p>
     * EN: Returns the id of the only valid session.
     *
     * @return el id de la única sesión válida / the id of the only valid session
     */
    public String getCurrentSession() { return currentSession; }

    /**
     * Devuelve la fecha de creación.
     * <p>
     * EN: Returns the creation date.
     *
     * @return la fecha de creación / the creation date
     */
    public LocalDateTime getCreated() { return created; }

    /**
     * Devuelve la fecha del último ingreso.
     * <p>
     * EN: Returns the last login date.
     *
     * @return la fecha del último ingreso / the last login date
     */
    public LocalDateTime getLastLogin() { return lastLogin; }
}

-- Usuario.java
CREATE TABLE USUARIO (
    ID                       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE                   VARCHAR2(80 CHAR) NOT NULL,
    USUARIO                  VARCHAR2(30 CHAR) NOT NULL CONSTRAINT UQ_USUARIO_USUARI UNIQUE,
    CLAVE                    VARCHAR2(100 CHAR) NOT NULL,
    ROL                      VARCHAR2(15 CHAR) NOT NULL CHECK (ROL IN ('ADMIN','DESPACHADOR','DOMICILIARIO')),
    ESTADO_CUENTA            VARCHAR2(12 CHAR) NOT NULL CHECK (ESTADO_CUENTA IN ('PENDIENTE','ACTIVO','INACTIVO','SUSPENDIDO','RECHAZADO')),
    DEBE_CAMBIAR_CLAVE       NUMBER(1) NOT NULL CHECK (DEBE_CAMBIAR_CLAVE IN (0,1)),
    SESION_ACTUAL            VARCHAR2(40 CHAR),
    CREADO                   TIMESTAMP NOT NULL,
    ULTIMO_INGRESO           TIMESTAMP
);


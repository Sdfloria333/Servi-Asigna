-- ---------------- Descripción de las tablas ----------------
COMMENT ON TABLE USUARIO IS 'Cuentas de acceso (ADMIN, DESPACHADOR, DOMICILIARIO). Clave en BCrypt. Borrado lógico por ESTADO_CUENTA.';
COMMENT ON TABLE POLITICA_DATOS IS 'Versiones de la política de tratamiento de datos y ubicación (Ley 1581 de 2012).';
COMMENT ON TABLE ACEPTACION_POLITICA IS 'Quién aceptó qué versión de la política, cuándo y desde qué IP.';
COMMENT ON TABLE PARAMETRO IS 'Parámetros de operación editables por el administrador (tiempos, motor, GPS, línea base).';
COMMENT ON TABLE TARIFA IS 'Tarifas: base + valor por km + recargos por tamaño. La vigente es ACTIVA=1.';
COMMENT ON TABLE CLIENTE IS 'Clientes frecuentes (búsqueda por teléfono).';
COMMENT ON TABLE DIRECCION IS 'Direcciones guardadas de cada cliente con su coordenada.';
COMMENT ON TABLE DOMICILIARIO IS 'Estado operativo del domiciliario. ID = USUARIO.ID.';
COMMENT ON TABLE VEHICULO IS 'Vehículo asignado y su capacidad en unidades.';
COMMENT ON TABLE DOCUMENTO_DOMICILIARIO IS 'Documentos con vencimiento (SOAT, licencia, tecnomecánica).';
COMMENT ON TABLE TURNO IS 'Turno del domiciliario: entregas, recaudo, ganancias, km.';
COMMENT ON TABLE RUTA IS 'Ruta de un domiciliario durante un turno.';
COMMENT ON TABLE SERVICIO IS 'Servicio de recogida y entrega (estado según la máquina de estados, sección 6.1).';
COMMENT ON TABLE PARADA IS 'Paradas (recoger/entregar) de cada servicio con su secuencia y horas estimadas.';
COMMENT ON TABLE OFERTA IS 'Ofertas enviadas a domiciliarios con temporizador y su respuesta.';
COMMENT ON TABLE HISTORIAL_ESTADO_SERVICIO IS 'Cada cambio de estado de un servicio: quién, cuándo, origen y motivo.';
COMMENT ON TABLE EVIDENCIA_ENTREGA IS 'Pruebas de entrega: PIN, foto o firma.';
COMMENT ON TABLE DECISION_MOTOR IS 'Registro de cada decisión del motor con los candidatos evaluados.';
COMMENT ON TABLE UBICACION_GPS IS 'Histórico de posiciones GPS (se depura según gps.retencion-dias).';
COMMENT ON TABLE INCIDENTE IS 'Novedades e incidentes reportados y la decisión de la central.';
COMMENT ON TABLE SEGUIMIENTO_INCIDENTE IS 'Comentarios de seguimiento de un incidente.';
COMMENT ON TABLE MENSAJE IS 'Mensajes entre la central y cada domiciliario.';
COMMENT ON TABLE PLANTILLA_MENSAJE IS 'Mensajes predefinidos.';
COMMENT ON TABLE AUDITORIA IS 'Acciones administrativas y de la central (INTERVENCION_MANUAL alimenta el indicador I7).';
COMMENT ON TABLE EVENTO_PROCESADO IS 'Eventos ya procesados enviados sin conexión (evita duplicados).';

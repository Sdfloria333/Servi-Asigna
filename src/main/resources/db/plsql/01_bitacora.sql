-- =====================================================================
-- 01 · Tabla de bitácora y procedimiento que la llena
-- Conectado como DESPACHO.
--
-- BITACORA_BD es una tabla NUEVA que solo usan los triggers de 05_triggers.sql.
-- La aplicación Java no la conoce ni la necesita (Hibernate no la mapea),
-- así que crearla o borrarla no cambia el funcionamiento del programa.
-- No reemplaza a HISTORIAL_ESTADO_SERVICIO ni a AUDITORIA (esas las llena Java):
-- registra lo que pasa en la BASE, venga de la aplicación o de alguien
-- que cambie datos a mano desde SQL Developer o VS Code.
-- =====================================================================

CREATE TABLE BITACORA_BD (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    TABLA           VARCHAR2(30 CHAR)  NOT NULL,
    REGISTRO_ID     VARCHAR2(60 CHAR),
    OPERACION       VARCHAR2(10 CHAR)  NOT NULL CHECK (OPERACION IN ('INSERT','UPDATE','DELETE')),
    CAMPO           VARCHAR2(30 CHAR),
    VALOR_ANTERIOR  VARCHAR2(300 CHAR),
    VALOR_NUEVO     VARCHAR2(300 CHAR),
    USUARIO_BD      VARCHAR2(30 CHAR)  NOT NULL,
    PROGRAMA        VARCHAR2(64 CHAR)
);

CREATE INDEX IX_BITA_FECHA ON BITACORA_BD (FECHA);
CREATE INDEX IX_BITA_TABLA ON BITACORA_BD (TABLA, REGISTRO_ID);

COMMENT ON TABLE  BITACORA_BD                IS 'Bitácora de cambios hecha por triggers (no la usa la aplicación Java).';
COMMENT ON COLUMN BITACORA_BD.TABLA          IS 'Tabla donde ocurrió el cambio.';
COMMENT ON COLUMN BITACORA_BD.REGISTRO_ID    IS 'ID (o clave) del registro que cambió.';
COMMENT ON COLUMN BITACORA_BD.OPERACION      IS 'INSERT, UPDATE o DELETE.';
COMMENT ON COLUMN BITACORA_BD.CAMPO          IS 'Columna que cambió (vacía si es el registro completo).';
COMMENT ON COLUMN BITACORA_BD.USUARIO_BD     IS 'Usuario de Oracle que hizo el cambio.';
COMMENT ON COLUMN BITACORA_BD.PROGRAMA       IS 'Programa conectado: "JDBC Thin Client" = la aplicación; otro = SQL Developer, VS Code, etc.';

-- ---------------------------------------------------------------------
-- PR_REGISTRAR_BITACORA: un solo lugar para escribir en la bitácora.
-- Los triggers lo llaman en vez de repetir el INSERT.
-- No es una transacción autónoma: si la operación que disparó el trigger
-- se deshace (ROLLBACK), su registro en la bitácora también se deshace.
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE PR_REGISTRAR_BITACORA (
    p_tabla      IN VARCHAR2,
    p_registro   IN VARCHAR2,
    p_operacion  IN VARCHAR2,
    p_campo      IN VARCHAR2 DEFAULT NULL,
    p_anterior   IN VARCHAR2 DEFAULT NULL,
    p_nuevo      IN VARCHAR2 DEFAULT NULL
) IS
BEGIN
    INSERT INTO BITACORA_BD (TABLA, REGISTRO_ID, OPERACION, CAMPO, VALOR_ANTERIOR, VALOR_NUEVO, USUARIO_BD, PROGRAMA)
    VALUES (p_tabla, p_registro, p_operacion, p_campo,
            SUBSTR(p_anterior, 1, 300), SUBSTR(p_nuevo, 1, 300),
            USER, SUBSTR(SYS_CONTEXT('USERENV', 'MODULE'), 1, 64));
END PR_REGISTRAR_BITACORA;
